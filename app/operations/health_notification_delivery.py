def process_health_notifications(
    *,
    repository: ArtifactRepository,
    incident_evaluation: dict[str, Any],
    health_report: dict[str, Any],
    health_run_id: str,
    now: datetime,
) -> dict[str, Any]:
    """Enqueue the current event and process all pending events."""

    event = build_notification_event(
        incident_evaluation=(
            incident_evaluation
        ),
        health_report=(
            health_report
        ),
        health_run_id=(
            health_run_id
        ),
        now=(
            now
        ),
    )

    enqueue_result = (
        enqueue_notification(
            repository=(
                repository
            ),
            event=(
                event
            ),
            now=(
                now
            ),
        )
    )

    channel = (
        read_notification_channel()
    )

    if channel == "email":
        email_client = (
            create_email_client()
        )

        delivery = (
            deliver_pending_email_notifications(
                repository=(
                    repository
                ),
                client=(
                    email_client
                ),
                now=(
                    now
                ),
            )
        )

    elif channel == "webhook":
        webhook_client = (
            create_webhook_client()
        )

        delivery = (
            deliver_pending_notifications(
                repository=(
                    repository
                ),
                client=(
                    webhook_client
                ),
                now=(
                    now
                ),
            )
        )

    else:
        outbox = load_outbox(
            repository
        )

        delivery = {
            "status": (
                "NOTIFICATION_DELIVERY_DISABLED"
            ),
            "channel": (
                "disabled"
            ),
            "attempted_count": 0,
            "delivered_count": 0,
            "failed_count": 0,
            "pending_count": len(
                outbox[
                    "pending"
                ]
            ),
            "delivered": [],
            "failures": [],
        }

    return {
        "event_created": (
            event is not None
        ),
        "notification_id": (
            event.get(
                "notification_id"
            )
            if event is not None
            else None
        ),
        "enqueued": (
            enqueue_result[
                "enqueued"
            ]
        ),
        **delivery,
    }